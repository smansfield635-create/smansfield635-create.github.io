function safePlainData(
  value,
  options = {}
) {
  const maxDepth =
    Number.isFinite(options.maxDepth)
      ? options.maxDepth
      : 9;

  const maxArrayLength =
    Number.isFinite(options.maxArrayLength)
      ? options.maxArrayLength
      : 220;

  const seen =
    new WeakSet();

  function visit(
    input,
    depth
  ) {
    if (input === null) {
      return null;
    }

    const inputType =
      typeof input;

    if (
      inputType === 'string' ||
      inputType === 'boolean'
    ) {
      return input;
    }

    if (inputType === 'number') {
      return Number.isFinite(input)
        ? input
        : String(input);
    }

    if (inputType === 'bigint') {
      return String(input);
    }

    if (inputType === 'symbol') {
      return String(input);
    }

    if (inputType === 'undefined') {
      return null;
    }

    if (inputType === 'function') {
      return `[Function ${input.name || 'anonymous'}]`;
    }

    if (depth > maxDepth) {
      return '[MaxDepthExceeded]';
    }

    if (inputType === 'object') {
      if (seen.has(input)) {
        return '[Circular]';
      }

      try {
        if (
          typeof Node !== 'undefined' &&
          input instanceof Node
        ) {
          return `[DOMNode ${input.nodeName || 'unknown'}]`;
        }
      } catch (_error) {
        // Continue as plain object.
      }

      seen.add(input);

      if (Array.isArray(input)) {
        const output =
          input
            .slice(
              0,
              maxArrayLength
            )
            .map(
              (entry) =>
                visit(
                  entry,
                  depth + 1
                )
            );

        if (
          input.length >
          maxArrayLength
        ) {
          output.push(
            `[ArrayTruncated ${
              input.length -
              maxArrayLength
            }]`
          );
        }

        return output;
      }

      const output = {};

      getOwnKeys(input)
        .forEach((key) => {
          if (
            key === 'document' ||
            key === 'ownerDocument' ||
            key === 'window' ||
            key === 'globalThis' ||
            key === 'routeRoot' ||
            key === 'mountNode' ||
            key === 'rendererMount' ||
            key === 'target' ||
            key === 'diagnosticWindow' ||
            key === 'publicRouteWindow'
          ) {
            output[key] =
              '[ContextOmitted]';

            return;
          }

          let nextValue;

          try {
            nextValue =
              input[key];
          } catch (error) {
            output[key] = {
              readFailed:
                true,

              errorName:
                error instanceof Error
                  ? error.name
                  : 'UnknownError',

              errorMessage:
                error instanceof Error
                  ? error.message
                  : String(error)
            };

            return;
          }

          output[key] =
            visit(
              nextValue,
              depth + 1
            );
        });

      return output;
    }

    return String(input);
  }

  return visit(
    value,
    0
  );
}


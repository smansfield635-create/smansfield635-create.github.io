async function executeDiagnosticOccurrence(
  occurrenceId,
  options = {}
) {
  try {
    const evidenceResolution =
      resolveEvidenceSource(
        options
      );

    if (
      !assertCurrentOccurrence(
        occurrenceId
      )
    ) {
      return freeze({
        receiptType:
          'H_EARTH_3D_DIAGNOSTIC_STALE_OCCURRENCE_RECEIPT',

        occurrenceId,

        status:
          'STALE_OCCURRENCE_IGNORED'
      });
    }

    await importDiagnosticDependencies(
      options
    );

    if (
      !assertCurrentOccurrence(
        occurrenceId
      )
    ) {
      return freeze({
        receiptType:
          'H_EARTH_3D_DIAGNOSTIC_STALE_OCCURRENCE_RECEIPT',

        occurrenceId,

        status:
          'STALE_OCCURRENCE_IGNORED'
      });
    }

    const publicRouteWindow =
      evidenceResolution
        .selectedWindow ||
      DIAGNOSTIC_STATE
        .diagnosticWindow ||
      globalThis;

    buildAllReports(
      publicRouteWindow
    );

    if (
      !assertCurrentOccurrence(
        occurrenceId
      )
    ) {
      return freeze({
        receiptType:
          'H_EARTH_3D_DIAGNOSTIC_STALE_OCCURRENCE_RECEIPT',

        occurrenceId,

        status:
          'STALE_OCCURRENCE_IGNORED'
      });
    }

    renderReports();
    setPanelStatusAttributes();

    const routeClass =
      DIAGNOSTIC_STATE
        .status ===
      'DIAGNOSTIC_READY'
        ? 'h-earth-3d-diagnostic-ready'
        : 'h-earth-3d-diagnostic-partial';

    setRouteClass(
      DIAGNOSTIC_STATE
        .mountPoints
        ?.routeRoot,
      routeClass
    );

    writeText(
      DIAGNOSTIC_STATE
        .mountPoints
        ?.status,
      DIAGNOSTIC_STATE
        .status
    );

    writeText(
      DIAGNOSTIC_STATE
        .mountPoints
        ?.statusNote,
      DIAGNOSTIC_STATE
        .status ===
      'DIAGNOSTIC_READY'
        ? 'Current route, compositor, renderer, custody, and boundary evidence has been assembled without diagnostic mutation.'
        : 'Diagnostic reporting completed with missing evidence or mismatches retained as held findings.'
    );

    writeText(
      DIAGNOSTIC_STATE
        .mountPoints
        ?.copyStatus,
      'Diagnostic reports are current. Run and copy controls are active.'
    );

    writeRouteDataset(
      'hEarthDiagnosticInitializationComplete',
      'true'
    );

    writeRouteDataset(
      'hEarthDiagnosticStatus',
      DIAGNOSTIC_STATE
        .status
    );

    DIAGNOSTIC_STATE.updatedAt =
      nowIso();

    publishActiveDiagnosticGlobals();

    return freeze({
      initialized:
        true,

      status:
        DIAGNOSTIC_STATE
          .status,

      initializationOccurrenceId:
        occurrenceId,

      diagnosticReceipt:
        DIAGNOSTIC_STATE
          .diagnosticReceipt,

      aggregateDiagnosticPayload:
        DIAGNOSTIC_STATE
          .aggregateDiagnosticPayload,

      boundary:
        H_EARTH_3D_DIAGNOSTIC_BOUNDARY_FLAGS
    });
  } catch (error) {
    if (
      !assertCurrentOccurrence(
        occurrenceId
      )
    ) {
      return freeze({
        receiptType:
          'H_EARTH_3D_DIAGNOSTIC_STALE_FAILURE_RECEIPT',

        occurrenceId,

        status:
          'STALE_FAILURE_IGNORED'
      });
    }

    const failureReceipt =
      buildFailureReceipt(
        error,
        'DIAGNOSTIC_EXECUTION'
      );

    renderFailure(
      failureReceipt
    );

    return failureReceipt;
  }
}

export function runHEarthDiagnostics(
  options = {}
) {
  if (
    DIAGNOSTIC_STATE
      .mountPoints
      ?.requiredFound !==
    true
  ) {
    const failureReceipt =
      freeze({
        receiptType:
          'H_EARTH_3D_DIAGNOSTIC_MOUNT_FAILURE',

        file:
          H_EARTH_3D_DIAGNOSTIC_FILE,

        contractId:
          H_EARTH_3D_DIAGNOSTIC_BOOTSTRAP_CONTRACT_ID,

        generatedAt:
          nowIso(),

        status:
          'DIAGNOSTIC_MOUNT_FAILURE',

        missingRequiredIds:
          DIAGNOSTIC_STATE
            .mountPoints
            ?.missingRequiredIds ||
          freezeArray([]),

        boundary:
          H_EARTH_3D_DIAGNOSTIC_BOUNDARY_FLAGS
      });

    renderFailure(
      failureReceipt
    );

    return Promise.resolve(
      failureReceipt
    );
  }

  const occurrenceId =
    createOccurrenceId();

  DIAGNOSTIC_STATE
    .initializationOccurrenceId =
      occurrenceId;

  DIAGNOSTIC_STATE.status =
    'DIAGNOSTIC_INITIALIZING';

  resetReportState();

  writeText(
    DIAGNOSTIC_STATE
      .mountPoints
      ?.status,
    'DIAGNOSTIC_INITIALIZING'
  );

  writeText(
    DIAGNOSTIC_STATE
      .mountPoints
      ?.statusNote,
    options.reason ===
    'MANUAL_RERUN'
      ? 'Refreshing current route, compositor, renderer, custody, and boundary evidence.'
      : 'Collecting current route, compositor, renderer, custody, and boundary evidence.'
  );

  writeText(
    DIAGNOSTIC_STATE
      .mountPoints
      ?.copyStatus,
    'Diagnostic evidence collection is in progress.'
  );

  writeRouteDataset(
    'hEarthDiagnosticInitializationComplete',
    'false'
  );

  const completionPromise =
    executeDiagnosticOccurrence(
      occurrenceId,
      {
        ...DIAGNOSTIC_STATE
          .options,

        ...options
      }
    );

  DIAGNOSTIC_STATE
    .completionPromise =
      completionPromise;

  globalThis
    .H_EARTH_3D_DIAGNOSTIC_COMPLETION_PROMISE =
      completionPromise;

  return completionPromise;
}

export function initializeHEarthDiagnosticRoute(
  options = {}
) {
  const rootDocument =
    getDocument(
      options
    );

  const diagnosticWindow =
    getDiagnosticWindow(
      options
    );

  releaseListenerOwnership();
  clearActiveDiagnosticGlobals();
  resetReportState();

  DIAGNOSTIC_STATE.rootDocument =
    rootDocument;

  DIAGNOSTIC_STATE.diagnosticWindow =
    diagnosticWindow;

  DIAGNOSTIC_STATE.options =
    freeze({
      ...options,

      document:
        rootDocument,

      diagnosticWindow
    });

  DIAGNOSTIC_STATE.generatedAt =
    nowIso();

  DIAGNOSTIC_STATE.mountPoints =
    resolveMountPoints(
      rootDocument
    );

  DIAGNOSTIC_STATE.initialized =
    DIAGNOSTIC_STATE
      .mountPoints
      .requiredFound;

  writeRouteDataset(
    'hEarthDiagnosticInitializationStarted',
    'true'
  );

  if (
    DIAGNOSTIC_STATE
      .mountPoints
      .publicRouteLink
  ) {
    DIAGNOSTIC_STATE
      .mountPoints
      .publicRouteLink
      .setAttribute(
        'href',
        H_EARTH_3D_PUBLIC_ROUTE
      );
  }

  if (
    !DIAGNOSTIC_STATE
      .mountPoints
      .requiredFound
  ) {
    DIAGNOSTIC_STATE.status =
      'DIAGNOSTIC_MOUNT_FAILURE';

    const failureReceipt =
      freeze({
        receiptType:
          'H_EARTH_3D_DIAGNOSTIC_MOUNT_FAILURE',

        file:
          H_EARTH_3D_DIAGNOSTIC_FILE,

        contractId:
          H_EARTH_3D_DIAGNOSTIC_BOOTSTRAP_CONTRACT_ID,

        generatedAt:
          nowIso(),

        status:
          'DIAGNOSTIC_MOUNT_FAILURE',

        missingRequiredIds:
          DIAGNOSTIC_STATE
            .mountPoints
            .missingRequiredIds,

        initialized:
          false,

        boundary:
          H_EARTH_3D_DIAGNOSTIC_BOUNDARY_FLAGS
      });

    renderFailure(
      failureReceipt
    );

    return freeze({
      initialized:
        false,

      status:
        'DIAGNOSTIC_MOUNT_FAILURE',

      missingRequiredIds:
        DIAGNOSTIC_STATE
          .mountPoints
          .missingRequiredIds,

      diagnosticReceipt:
        failureReceipt,

      boundary:
        H_EARTH_3D_DIAGNOSTIC_BOUNDARY_FLAGS
    });
  }

  const listenerReceipt =
    bindDiagnosticControls();

  DIAGNOSTIC_STATE.status =
    'DIAGNOSTIC_INITIALIZING';

  writeText(
    DIAGNOSTIC_STATE
      .mountPoints
      .status,
    'DIAGNOSTIC_INITIALIZING'
  );

  writeText(
    DIAGNOSTIC_STATE
      .mountPoints
      .statusNote,
    'Step 034U owns diagnostic evidence, report, run-control, copy-control, publication, completion, and teardown.'
  );

  writeText(
    DIAGNOSTIC_STATE
      .mountPoints
      .copyStatus,
    'Diagnostic controls are bound. Initial evidence collection is starting.'
  );

  writeJson(
    DIAGNOSTIC_STATE
      .mountPoints
      .reportLayerStatus,
    {
      receiptType:
        'H_EARTH_3D_DIAGNOSTIC_INITIALIZATION_RECEIPT',

      file:
        H_EARTH_3D_DIAGNOSTIC_FILE,

      contractId:
        H_EARTH_3D_DIAGNOSTIC_BOOTSTRAP_CONTRACT_ID,

      generatedAt:
        nowIso(),

      status:
        'DIAGNOSTIC_INITIALIZING',

      listenerReceipt,

      publicRouteInitializedByDiagnostic:
        false,

      rendererMountedByDiagnostic:
        false,

      boundary:
        H_EARTH_3D_DIAGNOSTIC_BOUNDARY_FLAGS
    }
  );

  const completionPromise =
    runHEarthDiagnostics({
      reason:
        'INITIAL_BOOTSTRAP'
    });

  return freeze({
    initialized:
      true,

    status:
      'DIAGNOSTIC_INITIALIZING',

    generatedAt:
      DIAGNOSTIC_STATE
        .generatedAt,

    initializationOccurrenceId:
      DIAGNOSTIC_STATE
        .initializationOccurrenceId,

    completionPromise,

    listenerReceipt,

    diagnosticRouteOnly:
      true,

    publicRouteInitializedByDiagnostic:
      false,

    packet002ConstructedByDiagnostic:
      false,

    admittedFrameConstructedByDiagnostic:
      false,

    compositorConstructedByDiagnostic:
      false,

    rendererConstructedByDiagnostic:
      false,

    rendererMountedByDiagnostic:
      false,

    rendererReleasedByDiagnostic:
      false,

    boundary:
      H_EARTH_3D_DIAGNOSTIC_BOUNDARY_FLAGS
  });
}

export function destroyHEarthDiagnosticRoute() {
  const priorOccurrenceId =
    DIAGNOSTIC_STATE
      .initializationOccurrenceId;

  releaseListenerOwnership();
  clearActiveDiagnosticGlobals();

  DIAGNOSTIC_STATE.initialized =
    false;

  DIAGNOSTIC_STATE.status =
    'DIAGNOSTIC_DESTROYED';

  DIAGNOSTIC_STATE.initializationOccurrenceId =
    null;

  DIAGNOSTIC_STATE.completionPromise =
    null;

  writeText(
    DIAGNOSTIC_STATE
      .mountPoints
      ?.status,
    'DIAGNOSTIC_DESTROYED'
  );

  writeText(
    DIAGNOSTIC_STATE
      .mountPoints
      ?.statusNote,
    'Diagnostic listeners, active diagnostic globals, and current occurrence ownership have been released.'
  );

  writeText(
    DIAGNOSTIC_STATE
      .mountPoints
      ?.copyStatus,
    'Diagnostic controls are no longer active.'
  );

  setRouteClass(
    DIAGNOSTIC_STATE
      .mountPoints
      ?.routeRoot,
    ''
  );

  writeRouteDataset(
    'hEarthDiagnosticInitializationStarted',
    'false'
  );

  writeRouteDataset(
    'hEarthDiagnosticInitializationComplete',
    'false'
  );

  return freeze({
    receiptType:
      'H_EARTH_3D_DIAGNOSTIC_DESTRUCTION_RECEIPT',

    file:
      H_EARTH_3D_DIAGNOSTIC_FILE,

    contractId:
      H_EARTH_3D_DIAGNOSTIC_BOOTSTRAP_CONTRACT_ID,

    generatedAt:
      nowIso(),

    priorOccurrenceId,

    status:
      'DIAGNOSTIC_DESTROYED',

    listenersReleased:
      true,

    activeDiagnosticGlobalsCleared:
      true,

    publicRouteMutation:
      false,

    rendererMutation:
      false,

    boundary:
      H_EARTH_3D_DIAGNOSTIC_BOUNDARY_FLAGS
  });
}


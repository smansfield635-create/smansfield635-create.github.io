import fs from 'node:fs';
import path from 'node:path';
const here=path.dirname(new URL(import.meta.url).pathname);
const read=n=>JSON.parse(fs.readFileSync(path.join(here,n),'utf8'));
const ok=(v,m)=>{if(!v)throw new Error(m)};
const s=read('versioned-study-registry.v1.json');
const c=read('canonical-coherence-object.v1.json');
const r=read('study-result-to-claim-typed-relation-registry.v1.json');
const p=read('claim-to-estate-projection-matrix.v1.json');
const q=read('claim-ceiling-propagation-table.v1.json');

/**
 * Contract-level guard for static review.
 * Returns false if a proposed claim breaches Step 034I boundaries.
 *
 * Recognized invariant facts return true because they are permitted
 * descriptor-read facts. Their factual Boolean values are reported separately
 * by classifyHEarthBoundaryClaim().
 */
export function isHEarthBoundaryClaimAllowed(claimName) {
  if (!claimName || typeof claimName !== 'string') return false;

  if (H_EARTH_BOUNDARY_CLAIM_CLASSIFICATION.blockedClaims.includes(claimName)) {
    return false;
  }

  if (
    H_EARTH_BOUNDARY_CLAIM_CLASSIFICATION.allowedDescriptorClaims.includes(claimName)
  ) {
    return true;
  }

  if (
    H_EARTH_BOUNDARY_CLAIM_CLASSIFICATION.invariantClaims.includes(claimName)
  ) {
    return true;
  }

  return false;
}

/**
 * Contract-level classifier.
 * This allows downstream consumers to distinguish admitted descriptor-stage
 * claims, recognized invariant facts, and blocked runtime/render/proof claims
 * without inferring from labels.
 */
export function classifyHEarthBoundaryClaim(claimName) {
  if (!claimName || typeof claimName !== 'string') {
    return Object.freeze({
      claimName,
      allowed: false,
      classification: 'INVALID_CLAIM_NAME',
      descriptorOnly: false,
      invariant: false,
      blocked: true
    });
  }

  if (H_EARTH_BOUNDARY_CLAIM_CLASSIFICATION.blockedClaims.includes(claimName)) {
    return Object.freeze({
      claimName,
      allowed: false,
      classification: 'BLOCKED_CLAIM',
      descriptorOnly: false,
      invariant: false,
      blocked: true
    });
  }

  if (
    H_EARTH_BOUNDARY_CLAIM_CLASSIFICATION.allowedDescriptorClaims.includes(claimName)
  ) {
    return Object.freeze({
      claimName,
      allowed: true,
      classification: 'ALLOWED_DESCRIPTOR_STAGE_CLAIM',
      descriptorOnly: true,
      invariant: false,
      blocked: false
    });
  }

  if (
    H_EARTH_BOUNDARY_CLAIM_CLASSIFICATION.invariantClaims.includes(claimName)
  ) {
    const invariantValue =
      H_EARTH_DOM_CSS_DESCRIPTOR_MOUNT_INVARIANTS[claimName];

    return Object.freeze({
      claimName,
      allowed: true,
      classification: 'BOUNDARY_INVARIANT_FACT',
      descriptorOnly: true,
      invariant: true,
      value: invariantValue,
      blocked: false
    });
  }

  return Object.freeze({
    claimName,
    allowed: false,
    classification: 'UNRECOGNIZED_CLAIM_HELD',
    descriptorOnly: false,
    invariant: false,
    blocked: true
  });
}


function augmentFd05PrimarySurface() {
  const documentObject = DIAGNOSTIC_STATE.rootDocument;
  const mount = getById(documentObject, FD05_PRIMARY_MOUNT_ID);
  const decision = DIAGNOSTIC_STATE.fd05DecisionReport;
  if (!mount || !decision) return false;

  const list = mount.querySelector('dl');
  if (!list) return false;

  function ensureRow(rowId, label, value) {
    let term = getById(documentObject, `${rowId}-term`);
    let detail = getById(documentObject, `${rowId}-detail`);
    if (!term || !detail) {
      term = documentObject.createElement('dt');
      detail = documentObject.createElement('dd');
      term.id = `${rowId}-term`;
      detail.id = `${rowId}-detail`;
      list.prepend(detail);
      list.prepend(term);
    }
    term.textContent = label;
    detail.textContent = String(value ?? 'NOT YET VERIFIED');
  }

  ensureRow(
    FD05_PRIMARY_STATUS_ROW_ID,
    'Primary receipt status',
    decision.primaryReceiptStatus
  );
  ensureRow(
    FD05_CLASSIFICATION_ROW_ID,
    'Instrument classification A–D',
    decision.instrumentClassification
  );
  mount.dataset.hEarthFd05InstrumentClassification = decision.instrumentClassification;
  return true;
}

function renderFd05Fallback() {
  const documentObject = DIAGNOSTIC_STATE.rootDocument;
  const host = DIAGNOSTIC_STATE.mountPoints?.fd05DecisionHost;
  const decision = DIAGNOSTIC_STATE.fd05DecisionReport;
  if (!documentObject || !host || !decision) return false;

  const primaryMount = getById(documentObject, FD05_PRIMARY_MOUNT_ID);
  let fallback = getById(documentObject, H_EARTH_3D_DIAGNOSTIC_PANEL_IDS.fd05FallbackPanel);

  if (primaryMount) {
    fallback?.remove();
    return augmentFd05PrimarySurface();
  }

  if (!fallback) {
    fallback = documentObject.createElement('article');
    fallback.id = H_EARTH_3D_DIAGNOSTIC_PANEL_IDS.fd05FallbackPanel;
    fallback.className =
      'h-earth-3d-diagnostic-panel h-earth-3d-panel-primary h-earth-3d-mismatch-panel';
    fallback.setAttribute('data-h-earth-panel-role', 'fd-05-watchdog-fallback');
    host.append(fallback);
  }

  fallback.replaceChildren();
  const heading = documentObject.createElement('div');
  heading.className = 'h-earth-3d-panel-heading-row';
  const headingCopy = documentObject.createElement('div');
  const kicker = documentObject.createElement('p');
  kicker.className = 'h-earth-3d-diagnostic-kicker';
  kicker.textContent = 'FD_05 Primary Lane';
  const title = documentObject.createElement('h2');
  title.textContent = 'Deployed ES Module Import Decision';
  headingCopy.append(kicker, title);
  const copyButton = documentObject.createElement('button');
  copyButton.className = 'h-earth-3d-copy-button h-earth-3d-panel-copy-button';
  copyButton.type = 'button';
  copyButton.textContent = 'Copy This Report';
  copyButton.addEventListener('click', () => {
    void copyDiagnosticPayload(toJson(decision, { maxDepth: 12, maxArrayLength: 420 }), 'FD_05 Decision');
  });
  heading.append(headingCopy, copyButton);
  const output = documentObject.createElement('pre');
  output.className = 'h-earth-3d-diagnostic-output';
  output.textContent = toJson(decision, { maxDepth: 12, maxArrayLength: 420 });
  fallback.append(heading, output);
  return true;
}

function safelyInvokeGetter(target, getterName) {
  if (!target || typeof target[getterName] !== 'function') {
    return freeze({ getter: getterName, available: false, invoked: false, succeeded: false, value: null });
  }
  try {
    return freeze({
      getter: getterName,
      available: true,
      invoked: true,
      succeeded: true,
      value: target[getterName]()
    });
  } catch (error) {
    return freeze({
      getter: getterName,
      available: true,
      invoked: true,
      succeeded: false,
      errorName: error instanceof Error ? error.name : 'UnknownError',
      errorMessage: error instanceof Error ? error.message : String(error),
      value: null
    });
  }
}


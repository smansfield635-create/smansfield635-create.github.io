function assertReplayResultShape(result, label) {
  if (!plainObject(result)) {
    throw new TypeError(
      `H_EARTH_REPLAY_RESULT_OBJECT_REQUIRED:${label}`
    );
  }

  if (!plainObject(result.snapshot)) {
    throw new TypeError(
      `H_EARTH_REPLAY_RESULT_SNAPSHOT_REQUIRED:${label}`
    );
  }

  if (!Array.isArray(result.events)) {
    throw new TypeError(
      `H_EARTH_REPLAY_RESULT_EVENTS_ARRAY_REQUIRED:${label}`
    );
  }

  if (!Array.isArray(result.pendingIntents)) {
    throw new TypeError(
      `H_EARTH_REPLAY_RESULT_PENDING_INTENTS_ARRAY_REQUIRED:${label}`
    );
  }
}

export function compareHEarthReplayResults(
  first,
  second
) {
  assertReplayResultShape(first, 'first');
  assertReplayResultShape(second, 'second');

  const checks =
    Object.freeze({
      finalStateHashEqual:
        first.snapshot
          .authoritativeStateHash ===
        second.snapshot
          .authoritativeStateHash,

      eventBatchHashEqual:
        first.snapshot
          .eventBatchHash ===
        second.snapshot
          .eventBatchHash,

      snapshotHashEqual:
        first.snapshot
          .snapshotHash ===
        second.snapshot
          .snapshotHash,

      eventCountEqual:
        first.events.length ===
        second.events.length,

      pendingIntentCountEqual:
        first.snapshot
          .pendingIntentCount ===
        second.snapshot
          .pendingIntentCount,

      pendingIntentQueueHashEqual:
        first.snapshot
          .pendingIntentQueueHash ===
        second.snapshot
          .pendingIntentQueueHash,

      rejectedSequenceEqual:
        canonicalizeHEarthValue(
          first.events.filter(
            (event) =>
              event.disposition ===
              'REJECTED'
          )
        ) ===
        canonicalizeHEarthValue(
          second.events.filter(
            (event) =>
              event.disposition ===
              'REJECTED'
          )
        ),

      committedSequenceEqual:
        canonicalizeHEarthValue(
          first.events.filter(
            (event) =>
              event.disposition ===
              'COMMITTED'
          )
        ) ===
        canonicalizeHEarthValue(
          second.events.filter(
            (event) =>
              event.disposition ===
              'COMMITTED'
          )
        )
    });

  const ok =
    Object.values(checks)
      .every(Boolean);

  return Object.freeze({
    ok,

    status:
      ok
        ? 'REPLAY_EQUALITY_DESCRIPTOR_MATCH'
        : 'REPLAY_DESCRIPTOR_MISMATCH',

    checks,

    descriptorComparisonOnly:
      true,

    replayProofClaim:
      false,

    liveProofClaim:
      false,

    validationClaim:
      false
  });
}


  function renderLensTabs(obj){
    lensTabs.replaceChildren();
    obj.lenses.forEach((name,index)=>{
      const btn=document.createElement('button');
      btn.type='button';
      btn.className='rf-lens-tab';
      btn.setAttribute('role','tab');
      btn.setAttribute('aria-selected',String(state.lens===name));
      btn.tabIndex=state.lens===name || (state.lens===null && index===0)?0:-1;
      btn.textContent=name;
      btn.addEventListener('click',()=>openLens(name));
      btn.addEventListener('keydown',(event)=>{
        if(event.key!=='ArrowLeft' && event.key!=='ArrowRight') return;
        event.preventDefault();
        const current=obj.lenses.indexOf(name);
        const next=(current+(event.key==='ArrowRight'?1:-1)+obj.lenses.length)%obj.lenses.length;
        openLens(obj.lenses[next],true);
      });
      lensTabs.appendChild(btn);
    });
    lensZone.hidden=false;
    if(state.lens===null){
      lensOutput.innerHTML='<strong>Evidence lenses are subordinate to this Evidence side.</strong> Select a source-supported lens to inspect the bounded attack, negative or missing evidence, reproduction boundary, or next test.';
    } else renderLensOutput(obj,state.lens);
  }

  function lensText(obj,name){
    switch(name){
      case 'Strongest Attack': return `The strongest attack is the boundary this object must survive without changing its frozen claim ceiling. Forbidden interpretation: ${obj.forbidden}`;
      case 'Evidence Held': return obj.evidence.join(' ');
      case 'Negative Result': return obj.negative || 'No source-supported negative-result lens is applicable to this object.';
      case 'Missing Evidence': return obj.missing || obj.unknown;
      case 'Reproduction Boundary': return obj.reproduction || obj.next;
      case 'Next Boundary': return obj.next;
      default: return '';
    }
  }

  function renderLensOutput(obj,name){
    lensOutput.innerHTML=`<strong>${esc(name)}</strong><p>${esc(lensText(obj,name))}</p>`;
    [...lensTabs.children].forEach(btn=>{
      const selected=btn.textContent===name;
      btn.setAttribute('aria-selected',String(selected));
      btn.tabIndex=selected?0:-1;
    });
  }

  function openLens(name,focus=false){
    const obj=objects[state.selected];
    if(!obj.lenses.includes(name)) return;
    state.lens=name;
    renderLensOutput(obj,name);
    if(focus) [...lensTabs.children].find(btn=>btn.textContent===name)?.focus();
  }

  function renderInspector(){
    const obj=objects[state.selected];
    inspectorId.textContent=obj.id;
    meaning.innerHTML=meaningHTML(obj);
    evidence.innerHTML=evidenceHTML(obj);
    panel.dataset.side=state.side;
    sideStatus.textContent=state.side==='meaning'?'Meaning side':'Evidence side';
    flipButton.setAttribute('aria-label','View the Other Side');
    flipButton.dataset.targetSide=state.side==='meaning'?'evidence':'meaning';
    const meaningActive=state.side==='meaning';
    meaningSide.setAttribute('aria-hidden',String(!meaningActive));
    evidenceSide.setAttribute('aria-hidden',String(meaningActive));
    meaningSide.inert=!meaningActive;
    evidenceSide.inert=meaningActive;
    if(!meaningActive) renderLensTabs(obj);
    else lensZone.hidden=true;
  }

  function openInspector(){
    state.side='meaning';
    state.bridge=false;
    state.lens=null;
    renderInspector();
    inspector.hidden=false;
    document.body.classList.add('rf-modal-open');
    requestAnimationFrame(()=>meaningSide.focus({preventScroll:true}));
  }

  function returnOrbit(){
    if(inspector.hidden) return;
    if(state.bridge){ closeBridge(); return; }
    inspector.hidden=true;
    document.body.classList.remove('rf-modal-open');
    track.children[state.selected]?.focus({preventScroll:true});
  }

  function flipSide(){
    if(state.bridge) return;
    state.side=state.side==='meaning'?'evidence':'meaning';
    state.lens=null;
    renderInspector();
    const target=state.side==='meaning'?meaningSide:evidenceSide;
    requestAnimationFrame(()=>target.focus({preventScroll:true}));
  }


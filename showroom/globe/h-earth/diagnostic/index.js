function freeze(value) {
  return Object.freeze(value);
}

function freezeArray(value) {
  return freeze([
    ...value
  ]);
}

function isObjectLike(value) {
  return (
    value !== null &&
    (
      typeof value === 'object' ||
      typeof value === 'function'
    )
  );
}

function getOwnKeys(value) {
  if (!isObjectLike(value)) {
    return [];
  }

  try {
    return Object.keys(value);
  } catch (_error) {
    return [];
  }
}


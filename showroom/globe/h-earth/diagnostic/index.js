function normalizeCandidateWindowEntries(
  options = {}
) {
  const candidates = [];

  if (
    Array.isArray(
      options
        .candidatePublicRouteWindows
    )
  ) {
    options
      .candidatePublicRouteWindows
      .forEach(
        (
          candidate,
          index
        ) => {
          if (
            candidate &&
            isObjectLike(
              candidate.window
            )
          ) {
            candidates.push({
              source:
                candidate.source ||
                `candidate-${index}`,

              window:
                candidate.window
            });

            return;
          }

          if (
            isObjectLike(
              candidate
            )
          ) {
            candidates.push({
              source:
                `candidate-${index}`,

              window:
                candidate
            });
          }
        }
      );
  }

  if (
    isObjectLike(
      options.publicRouteWindow
    )
  ) {
    candidates.push({
      source:
        'options.publicRouteWindow',

      window:
        options.publicRouteWindow
    });
  }

  if (
    isObjectLike(
      options.diagnosticWindow
    )
  ) {
    candidates.push({
      source:
        'options.diagnosticWindow',

      window:
        options.diagnosticWindow
    });
  }

  if (
    candidates.length ===
    0
  ) {
    candidates.push({
      source:
        'globalThis',

      window:
        globalThis
    });
  }

  const seen =
    new Set();

  return freezeArray(
    candidates.filter(
      (candidate) => {
        if (
          seen.has(
            candidate.window
          )
        ) {
          return false;
        }

        seen.add(
          candidate.window
        );

        return true;
      }
    )
  );
}


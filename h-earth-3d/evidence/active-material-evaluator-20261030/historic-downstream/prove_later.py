    assert set(tris)==set(EXPECTED_OFFSETS)
    for k,ids in EXPECTED_TRI_IDS.items():
        assert tris[k]['ids']==ids,('OFFSET_IDENTITY_DRIFT',k)
        assert tris[k]['contact']==[64,64,64],('CONTACT_NOT_SATURATED',k)

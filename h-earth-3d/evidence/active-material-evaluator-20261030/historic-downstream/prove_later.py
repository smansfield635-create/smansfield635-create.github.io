ROOT=Path(__file__).parent
TARGETS=[(-188.875,14.75439453125,-736.0625),(-189.0625,14.73388671875,-734.5625)]
EXPECTED_OFFSETS=(144,73902)
EXPECTED_TRI_IDS={144:[24,121,25],73902:[14742,14740,14741]}
# Exact frozen Gen3000 ordered-material.json, source blob ebb5f2cad7e7a433eef799548d946adac6e9eb5e
HABITAT_BOUNDS=[[-213,-298,-69,-154],[-298,-570,88,-154],[-448,-283,448,-93]]
SUBSTRATE_RECEIPT_SHA='6e472b56dd2cf45f437b54359cecb3b60a39a402b8cc295052a79d7744c78b31'

def smooth(a,b,x):
    t=min(1,max(0,(x-a)/(b-a)))
    return t*t*(3-2*t)

def source_guards(x,y,z,contact):
    w=(x,z); dist=math.hypot(x-80,z+172)
    manor_env=1-smooth(7,30,dist)
    def ring(inner,outer,feather):return smooth(inner-feather,inner+feather,dist)*(1-smooth(outer-feather,outer+feather,dist))
    manor_rings=[ring(10.5,21,2.2),ring(21.5,31.5,2.4),ring(4.5,13.5,1.8)]
    # Site B includes the exact bounded mountain-contact mask. The extra
    # exp(-((x-40)/18)^2) is deliberately not approximated as zero.
    mountain_edge=min(x+120,96-x,z+376,-224-z)
    site_b_contact=smooth(0,12,mountain_edge)
    divider=-208 if x<=-52 else None
    if divider is None:raise AssertionError('DOMAIN_EXPECTS_X_LESS_THAN_NEG52')
    hillside=smooth(-48,-24,z-divider)
    sand_window=1-smooth(10,38,contact)
    shoreline_uv=[(x+18)/52,(z+204)/73]
    shoreline_inside=all(0<=v<=1 for v in shoreline_uv)
    litter_domain=(-180<x<-24 and -380<z<-190)
    # Native shader covers strictly interior panel coordinates, after half-texel clamp.
    habitat_inside=[b[0]<x<b[2] and b[1]<z<b[3] for b in HABITAT_BOUNDS]
    bank_window=smooth(-22,-14,x)*(1-smooth(30,38,x))*smooth(-208,-200,z)*(1-smooth(-135,-127,z))
    checks={
      'manorFourOps':manor_env==0 and all(v==0 for v in manor_rings),
      'siteB':site_b_contact==0,
      'steepBank':hillside==0,
      'sand':sand_window==0,
      'shorelineRootSoil':not shoreline_inside,
      'woodlandLitter':not litter_domain,
      'habitat':not any(habitat_inside),
      'bankGravel':bank_window==0
    }
    return dict(world=[x,y,z],contact=contact,manorRadius=dist,
      mountainContactEdge=mountain_edge,hillsideDivider=divider,
      hillsideArgument=z-divider,shorelineUV=shoreline_uv,
      habitatPanelsInside=habitat_inside,stageInactivity=checks,
      allPostMarginStagesInactive=all(checks.values()))


ok(claims.size===c.claims.length,'duplicate claim id');
ok(s.studies.length===21,'portfolio count drift');
ok(r.relations.length===36,'typed relation count drift');
for(const v of r.relations){ok(ids.has(v.studyId),'relation missing study '+v.studyId);ok(claims.has(v.claimId),'relation missing claim '+v.claimId)}
for(const v of p.matrix)ok(claims.has(v.claimId),'projection missing claim '+v.claimId);
ok(c.scientificStatus==='ACTIVE_SCIENTIFIC_CANDIDATE','candidate status drift');
ok(c.claimCeiling==='EMPIRICAL_UNIVERSALITY_NOT_ESTABLISHED','universality promotion');
ok(c.claims.find(v=>v.claimId==='UCIC_CLAIM_MULTIPLICATIVE_SPECIFICITY').status==='REJECTED_AS_UNIVERSAL','multiplicative revival');
ok(c.claims.find(v=>v.claimId==='UCIC_CLAIM_GENERAL_OBSERVATIONAL_PREDICTIVE_SUPERIORITY').status==='NOT_SUPPORTED','observational superiority promotion');
ok(c.claims.find(v=>v.claimId==='UCIC_CLAIM_EMPIRICAL_UNIVERSALITY').status==='NOT_ESTABLISHED','universality drift');
ok(s.studies.some(v=>v.admission==='LEVEL_B_PORTFOLIO_RECORD'),'missing Level B');
ok(s.studies.some(v=>v.admission==='LEVEL_C_HISTORICAL_QUARANTINED'),'missing quarantine');
ok(u.records.some(v=>v.status==='PROTOCOL_ONLY'),'protocol-only collapse');
ok(x.records.some(v=>v.class==='SUPERSESSION_WITH_QUARANTINE'),'supersession semantics missing');
ok(a.preservedExistingEntries.includes('BIO_LAB')&&a.preservedExistingEntries.includes('HURRICANE_RAW_TC_RADAR_QC_CORRECTED'),'existing F4 entries not preserved');

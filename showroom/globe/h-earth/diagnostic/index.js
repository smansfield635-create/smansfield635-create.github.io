function normalizeCandidateWindowEntries(options = {}) {
  const candidates = [];
  if (Array.isArray(options.candidatePublicRouteWindows)) {
    options.candidatePublicRouteWindows.forEach((candidate, index) => {
      if (candidate && isObjectLike(candidate.window)) {
        candidates.push({ source: candidate.source || `candidate-${index}`, window: candidate.window });
      } else if (isObjectLike(candidate)) {
        candidates.push({ source: `candidate-${index}`, window: candidate });
      }
    });
  }
  if (isObjectLike(options.publicRouteWindow)) {
    candidates.push({ source: 'options.publicRouteWindow', window: options.publicRouteWindow });
  }
  if (isObjectLike(options.diagnosticWindow)) {
    candidates.push({ source: 'options.diagnosticWindow', window: options.diagnosticWindow });
  }
  if (candidates.length === 0) candidates.push({ source: 'globalThis', window: globalThis });
  const seen = new Set();
  return freezeArray(
    candidates.filter((candidate) => {
      if (seen.has(candidate.window)) return false;
      seen.add(candidate.window);
      return true;
    })
  );
}

function inspectCandidateWindow(candidate) {
  try {
    const candidateWindow = candidate.window;
    const locationHref =
      typeof candidateWindow?.location?.href === 'string' ? candidateWindow.location.href : null;
    const locationPathname =
      typeof candidateWindow?.location?.pathname === 'string'
        ? candidateWindow.location.pathname
        : null;
    const keys = [
      'H_EARTH_3D_INDEX',
      'H_EARTH_3D_ROUTE_BOOTSTRAP_RECEIPT',
      'H_EARTH_3D_ROUTE_BOOTSTRAP_STATUS',
      'H_EARTH_3D_ROUTE_BOOTSTRAP_RESULT',
      'H_EARTH_3D_ROUTE_BOOTSTRAP_COMPLETION',
      'H_EARTH_3D_LAYER_4_STATUS_PROJECTION',
      'H_EARTH_3D_LAYER_4_PUBLIC_STAGE_RECEIPT',
      'H_EARTH_3D_PUBLIC_STAGE_SOURCE_PREVIEW_RECEIPT',
      'H_EARTH_3D_PUBLIC_STAGE_ASYNC_FAILURE'
    ];
    const observedKeys = keys.filter((key) => readGlobalReceipt(candidateWindow, key) !== null);
    return freeze({
      source: candidate.source,
      accessible: true,
      locationHref,
      locationPathname,
      publicRoutePathObserved: locationPathname === H_EARTH_3D_PUBLIC_ROUTE,
      publicRouteEvidenceCount: observedKeys.length,
      publicRouteEvidencePresent: observedKeys.length > 0,
      observedKeys: freezeArray(observedKeys),
      window: candidateWindow
    });
  } catch (error) {
    return freeze({
      source: candidate.source,
      accessible: false,
      publicRoutePathObserved: false,
      publicRouteEvidenceCount: 0,
      publicRouteEvidencePresent: false,
      errorName: error instanceof Error ? error.name : 'UnknownError',
      errorMessage: error instanceof Error ? error.message : String(error),
      window: null
    });
  }
}

function resolveEvidenceSource(options = {}) {
  const candidates = normalizeCandidateWindowEntries(options);
  const inspections = candidates.map(inspectCandidateWindow);
  const selectedInspection =
    inspections
      .filter((inspection) => inspection.accessible === true)
      .sort((left, right) => {
        if (left.publicRoutePathObserved !== right.publicRoutePathObserved) {
          return left.publicRoutePathObserved ? -1 : 1;
        }
        return right.publicRouteEvidenceCount - left.publicRouteEvidenceCount;
      })[0] || null;

  const report = freeze({
    receiptType: 'H_EARTH_3D_DIAGNOSTIC_EVIDENCE_SOURCE_REPORT',
    file: H_EARTH_3D_DIAGNOSTIC_FILE,
    contractId: H_EARTH_3D_DIAGNOSTIC_BOOTSTRAP_CONTRACT_ID,
    generatedAt: nowIso(),
    candidateCount: candidates.length,
    accessibleCandidateCount: inspections.filter((entry) => entry.accessible).length,
    selectedSource: selectedInspection?.source || 'NONE',
    selectedLocationHref: selectedInspection?.locationHref || null,
    selectedLocationPathname: selectedInspection?.locationPathname || null,
    selectedPublicRoutePathObserved: selectedInspection?.publicRoutePathObserved === true,
    livePublicRouteEvidenceObserved: selectedInspection?.publicRouteEvidencePresent === true,
    selectedEvidenceCount: selectedInspection?.publicRouteEvidenceCount || 0,
    candidateInspections: freezeArray(inspections.map((entry) => safePlainData(entry))),
    fallbackPolicy:
      'USE_STATIC_MODULE_IMPORTS_AND_EXPLICIT_ABSENCE_REPORTING_WHEN_LIVE_WINDOW_EVIDENCE_IS_UNAVAILABLE',
    publicRouteInitializedByDiagnostic: false,
    publicRouteMutation: false,
    boundary: H_EARTH_3D_DIAGNOSTIC_BOUNDARY_FLAGS
  });

  DIAGNOSTIC_STATE.evidenceSourceReport = report;
  writeRouteDataset('hEarthDiagnosticEvidenceSource', report.selectedSource);
  writeRouteDataset(
    'hEarthLivePublicRouteEvidenceObserved',
    String(report.livePublicRouteEvidenceObserved)
  );
  return freeze({ report, selectedWindow: selectedInspection?.window || null });
}


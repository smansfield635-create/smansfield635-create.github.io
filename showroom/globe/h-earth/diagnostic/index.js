async function copyDiagnosticPayload(
  text,
  label
) {
  const copyStatus =
    DIAGNOSTIC_STATE
      .mountPoints
      ?.copyStatus;

  if (!text.trim()) {
    writeText(
      copyStatus,
      `${label} copy skipped: payload is empty.`
    );

    return false;
  }

  try {
    const copied =
      await copyText(
        text
      );

    writeText(
      copyStatus,
      copied
        ? `${label} copied.`
        : `${label} copy failed: clipboard support is unavailable.`
    );

    if (copyStatus?.dataset) {
      copyStatus.dataset
        .hEarthCopyState =
          copied
            ? 'success'
            : 'failure';
    }

    return copied;
  } catch (error) {
    writeText(
      copyStatus,
      `${label} copy failed: ${
        error instanceof Error
          ? error.message
          : String(error)
      }`
    );

    if (copyStatus?.dataset) {
      copyStatus.dataset
        .hEarthCopyState =
          'failure';
    }

    return false;
  }
}


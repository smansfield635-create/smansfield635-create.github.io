function deriveDiagnosticStatus() {
  if (
    DIAGNOSTIC_STATE
      .mountPoints
      ?.requiredFound !==
    true
  ) {
    return 'DIAGNOSTIC_MOUNT_FAILURE';
  }

  const mismatchStatus =
    DIAGNOSTIC_STATE
      .boundaryMismatchReport
      ?.status;

  if (
    mismatchStatus ===
    'MISMATCH_FOUND'
  ) {
    return 'DIAGNOSTIC_PARTIAL';
  }

  if (
    mismatchStatus ===
    'EVIDENCE_INCOMPLETE'
  ) {
    return 'DIAGNOSTIC_PARTIAL';
  }

  return 'DIAGNOSTIC_READY';
}


ok(a.newLevelAObjects.length===14,'Level-A augmentation count drift');
ok(a.f7AccessibilityInheritance.objectSpecificControlSemanticsCreated===false,'F7 semantic override');
ok(q.forbiddenPromotions.includes('PROJECTION_UNIVERSALITY_PROMOTION'),'claim ceiling guard missing');
ok(e.canonicalObjectId==='UNIVERSAL_COHERENCE_CONSTRUCT','canonical object drift');
ok(z.f8Inputs.length===3,'F8 semantic input count drift');
ok(z.publicMutation===false&&z.geometry===false&&z.f8Construction===false&&z.scientificClaimUpgrade===false,'stop-boundary violation');
console.log(JSON.stringify({status:'PASS_PRE_F8_CORRECTIVE_CONSTRUCTION_v1',studies:s.studies.length,claims:c.claims.length,relations:r.relations.length,newLevelA:a.newLevelAObjects.length,f8Inputs:z.f8Inputs},null,2));

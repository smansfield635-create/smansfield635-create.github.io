function addOwnedListener(
  target,
  type,
  listener
) {
  if (
    !target ||
    typeof target.addEventListener !==
      'function'
  ) {
    return false;
  }

  const controller =
    DIAGNOSTIC_STATE
      .listenerAbortController;

  if (
    controller
      ?.signal
  ) {
    try {
      target.addEventListener(
        type,
        listener,
        {
          signal:
            controller.signal
        }
      );

      return true;
    } catch (_error) {
      // Manual fallback follows.
    }
  }

  target.addEventListener(
    type,
    listener
  );

  DIAGNOSTIC_STATE
    .manualListenerRemovers
    .push(
      () => {
        target.removeEventListener(
          type,
          listener
        );
      }
    );

  return true;
}

async function copyText(
  text
) {
  if (
    globalThis.navigator
      ?.clipboard &&
    typeof globalThis
      .navigator
      .clipboard
      .writeText ===
      'function'
  ) {
    await globalThis
      .navigator
      .clipboard
      .writeText(
        text
      );

    return true;
  }

  const rootDocument =
    DIAGNOSTIC_STATE
      .rootDocument;

  if (
    !rootDocument
      ?.body ||
    typeof rootDocument
      .createElement !==
      'function'
  ) {
    return false;
  }

  const textarea =
    rootDocument
      .createElement(
        'textarea'
      );

  textarea.value =
    text;

  textarea.setAttribute(
    'readonly',
    'true'
  );

  textarea.style.position =
    'fixed';

  textarea.style.left =
    '-9999px';

  textarea.style.top =
    '0';

  rootDocument.body
    .appendChild(
      textarea
    );

  textarea.focus();
  textarea.select();

  let copied =
    false;

  try {
    copied =
      rootDocument.execCommand(
        'copy'
      );
  } finally {
    textarea.remove();
  }

  return copied;
}

